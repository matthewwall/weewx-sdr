    """TEST_CASES stays in sync with every class EXAMPLES."""
    keys = {
        f'{name}.EXAMPLES[{i}]'
        for name, cls in inspect.getmembers(brands, inspect.isclass)
        for i in range(len(getattr(cls, 'EXAMPLES', ())))
    }
    assert {case.id for case in TEST_CASES} == keys


